# --- Step 2: Data Loader (Local CSVs) ---
def load_data():
    """Load, merge, and cache the Walmart dataset."""
    raw_path = "./data/raw/"
    data_path = "./data/"
    os.makedirs(raw_path, exist_ok=True)
    os.makedirs(data_path, exist_ok=True)

    master_file = os.path.join(data_path, "master_data.parquet")

    if os.path.exists(master_file):
        print("[INFO] Found cached master_data.parquet. Loading...")
        return pd.read_parquet(master_file)

    required = ['train.csv', 'features.csv', 'stores.csv']
    if all(os.path.exists(os.path.join(raw_path, f)) for f in required):
        print("[INFO] Found raw CSVs locally. Loading and merging...")
        train = pd.read_csv(os.path.join(raw_path, "train.csv"))
        features = pd.read_csv(os.path.join(raw_path, "features.csv"))
        stores = pd.read_csv(os.path.join(raw_path, "stores.csv"))

        df = train.merge(features, on=['Store', 'Date', 'IsHoliday'], how='left')
        df = df.merge(stores, on=['Store'], how='left')
        df['Date'] = pd.to_datetime(df['Date'])
        df = df.sort_values(by=['Store', 'Dept', 'Date']).reset_index(drop=True)
        df['SKU'] = df['Store'].astype(str) + "_" + df['Dept'].astype(str)
        df.to_parquet(master_file)
        print("[INFO] Merged and cached as master_data.parquet.")
        return df

    print("=" * 60)
    print("[ERROR] CSV files not found!")
    print("Please place the following 3 files in './data/raw/':")
    print("  - train.csv")
    print("  - features.csv")
    print("  - stores.csv")
